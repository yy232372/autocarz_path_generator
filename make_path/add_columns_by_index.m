% add_columns_by_index.m
% 기존 2열(X, Y) 경로 데이터를 불러와서 인덱스마다 3번째, 4번째 열의 값을 부여하는 코드

clc; clear;

% 파일 로드 (구분자 자동 인식)
% 사용할 txt 파일 이름을 지정해주세요.
data = readmatrix('in_new1.txt');

% 파일 읽기 검증 (열 개수 확인)
if size(data, 2) < 2
    error('오류: 파일을 읽어들였지만 열(Column) 개수가 2개 미만입니다. 텍스트 파일의 구분자(콤마, 띄어쓰기 등)를 확인해주세요.');
end

num_points = size(data, 1);

% 3번째 열과 4번째 열 초기화 (전체 구간 기본값 설정)
col3 = zeros(num_points, 1); % 3번째 열 기본값: 0
col4 = ones(num_points, 1);  % 4번째 열 기본값: 1

% =========================================================
% 특정 인덱스 구간에 대해 3, 4번째 열의 값 할당
% 필요하신 인덱스 구간과 값을 아래처럼 주석을 풀고 입력하세요.
% =========================================================

col3(295:390) = 1;
col3(840:945) = 1;  



col3(211:245) = 4; 
col3(583:618) = 4;





% =========================================================
% 기존 데이터(X, Y)에 3, 4번째 열 추가하여 최종 행렬 생성
% 만약 입력 파일이 이미 여러 열을 가지고 있다면 데이터(:, 1:2)로 앞의 X,Y만 가져옵니다.
output_data = [data(:, 1:2), col3, col4];

% 결과 저장
output_filename = 'new_in_index.txt';
writematrix(output_data, output_filename, 'Delimiter', '\t');

fprintf('성공적으로 3, 4번째 열의 데이터가 추가되어 %s 파일로 저장되었습니다.\n', output_filename);
